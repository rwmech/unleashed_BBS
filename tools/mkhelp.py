#
#               The words live in internal/long-help-2026-09-22.md, where a
#               person can read and edit them as prose with a ruler at the
#               top. This turns them into a table, so the text in the
#               firmware cannot drift from the text somebody reviewed:
#               change the prose, run this, and the table follows.
#
#               It also refuses what would be wrong on a caller's screen:
#               a line over 39 columns (a C64 wraps the 40th) and any
#               character a C64 cannot show.
